// Linear interpolation helper for collision integrals
double linear_interp(double x,
                     const std::vector<double>& x_values,
                     const std::vector<double>& y_values)
{
    if (x_values.size() != y_values.size()) {
        throw std::invalid_argument("linear_interp: x_values and y_values must have the same size");
    }
    if (x_values.size() < 2) {
        throw std::invalid_argument("linear_interp: at least two points are required");
    }

    auto it = std::lower_bound(x_values.begin(), x_values.end(), x);

    if (it == x_values.begin()) {
        return y_values.front();
    }
    if (it == x_values.end()) {
        return y_values.back();
    }

    std::size_t idx = static_cast<std::size_t>(std::distance(x_values.begin(), it) - 1);

    double x0 = x_values[idx];
    double x1 = x_values[idx + 1];
    double y0 = y_values[idx];
    double y1 = y_values[idx + 1];

    if (x1 == x0) {
        throw std::invalid_argument("linear_interp: x_values must be strictly increasing");
    }

    double t = (x - x0) / (x1 - x0);
    return y0 + t * (y1 - y0);
}

// Collision integral Omega*(2,2)(T*, delta*): quintic Hermite in
// (ln T*, ln Omega*) on the Monchick-Mason grid, with the node values, slopes
// AND curvatures from include/collision_integral_data.h (generated by
// thermo_data_generator/collision_integrals.py). delta* = 0 is exact
// Lennard-Jones (quadrature, checked against Kim & Monroe 2014); delta* > 0 is
// Monchick & Mason (1961) with estimated slopes and curvatures. C2 in T*, so
// viscosity and conductivity have a continuous second temperature derivative
// (#611; the cubic Hermite of #485 stepped it 0.1-10% at every node); linear
// in delta*, which is constant per species. Linear interpolation in raw T*
// (before #485) erred by up to 2.7% between nodes and put 2-17% kinks in
// dmu/dT.
//
// Outside 0.1 <= T* <= 400 the curve continues linearly in (ln T*, ln Omega*)
// with the end slope (C2 at the edge: the end curvature is zero): a power law,
// which is the form the collision integral takes at both extremes.
namespace {

struct LogTable {
    double lx[collision::kNumTStar];
    double ly[collision::kNumTStar * collision::kNumDelta];
};

const LogTable& log_table() {
    static const LogTable t = [] {
        LogTable r{};
        for (int k = 0; k < collision::kNumTStar; ++k) {
            r.lx[k] = std::log(collision::kTStar[k]);
        }
        for (int k = 0; k < collision::kNumTStar * collision::kNumDelta; ++k) {
            r.ly[k] = std::log(collision::kOmega22[k]);
        }
        return r;
    }();
    return t;
}

// ln Omega* and d ln Omega* / d ln T* in delta* column c at ln T* = lx.
void column_ln_omega(int c, double lx, double& ln_om, double& dln) {
    const LogTable& t = log_table();
    constexpr int nT = collision::kNumTStar;
    constexpr int nD = collision::kNumDelta;
    if (lx <= t.lx[0] || lx >= t.lx[nT - 1]) {
        const int k = (lx <= t.lx[0]) ? 0 : nT - 1;
        dln = collision::kDlnOmega22DlnT[k * nD + c];
        ln_om = t.ly[k * nD + c] + dln * (lx - t.lx[k]);
        return;
    }
    int i = nT - 2;
    for (int k = 0; k < nT - 1; ++k) {
        if (lx <= t.lx[k + 1]) {
            i = k;
            break;
        }
    }
    const double h = t.lx[i + 1] - t.lx[i];
    const double u = (lx - t.lx[i]) / h;
    const double y0 = t.ly[i * nD + c];
    const double y1 = t.ly[(i + 1) * nD + c];
    const double m0 = collision::kDlnOmega22DlnT[i * nD + c] * h;
    const double m1 = collision::kDlnOmega22DlnT[(i + 1) * nD + c] * h;
    const double c0 = collision::kD2lnOmega22DlnT2[i * nD + c] * h * h;
    const double c1 = collision::kD2lnOmega22DlnT2[(i + 1) * nD + c] * h * h;
    const double u2 = u * u;
    const double u3 = u2 * u;
    const double u4 = u3 * u;
    const double u5 = u4 * u;
    // Quintic Hermite basis: value, slope and curvature at each end.
    ln_om = (1 - 10 * u3 + 15 * u4 - 6 * u5) * y0 + (u - 6 * u3 + 8 * u4 - 3 * u5) * m0 +
            0.5 * (u2 - 3 * u3 + 3 * u4 - u5) * c0 + (10 * u3 - 15 * u4 + 6 * u5) * y1 +
            (-4 * u3 + 7 * u4 - 3 * u5) * m1 + 0.5 * (u3 - 2 * u4 + u5) * c1;
    dln = ((-30 * u2 + 60 * u3 - 30 * u4) * y0 + (1 - 18 * u2 + 32 * u3 - 15 * u4) * m0 +
           0.5 * (2 * u - 9 * u2 + 12 * u3 - 5 * u4) * c0 +
           (30 * u2 - 60 * u3 + 30 * u4) * y1 + (-12 * u2 + 28 * u3 - 15 * u4) * m1 +
           0.5 * (3 * u2 - 8 * u3 + 5 * u4) * c1) /
          h;
}

}  // namespace

Omega22Result omega22_and_derivative(double T_star, double delta_star)
{
    constexpr int nD = collision::kNumDelta;
    const double ts = std::max(T_star, 1e-6);
    const double ds = std::max(0.0, std::min(delta_star, collision::kDelta[nD - 1]));
    int iD = nD - 2;
    for (int k = 0; k < nD - 1; ++k) {
        if (ds <= collision::kDelta[k + 1]) {
            iD = k;
            break;
        }
    }
    const double fD = (ds - collision::kDelta[iD]) / (collision::kDelta[iD + 1] - collision::kDelta[iD]);
    const double lx = std::log(ts);
    double l0, d0, l1, d1;
    column_ln_omega(iD, lx, l0, d0);
    column_ln_omega(iD + 1, lx, l1, d1);
    const double om0 = std::exp(l0);
    const double om1 = std::exp(l1);
    Omega22Result r;
    r.omega = (1.0 - fD) * om0 + fD * om1;
    // d Omega/d T* = Omega * (d ln Omega / d ln T*) / T*, per column.
    r.domega_dTstar = ((1.0 - fD) * om0 * d0 + fD * om1 * d1) / ts;
    return r;
}

double omega22(double T_star, double delta_star)
{
    return omega22_and_derivative(T_star, delta_star).omega;
}

