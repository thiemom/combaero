// Reduced dipole moment (Stockmayer parameter) delta*.
// well_depth_K in K, diameter_A in Angstrom, dipole_D in Debye.
double compute_delta_star(double well_depth_K, double diameter_A, double dipole_D)
{
    if (dipole_D == 0.0) return 0.0;
    constexpr double K_E     = 8.98755e9;    // N*m^2/C^2  (1/4*pi*eps0)
    constexpr double D_TO_CM = 3.33564e-30;  // C*m per Debye
    const double mu_SI  = dipole_D * D_TO_CM;
    const double eps_SI = well_depth_K * thermo::BOLTZMANN;
    const double sig_m  = diameter_A * 1.0e-10;
    return K_E * mu_SI * mu_SI / (2.0 * eps_SI * sig_m * sig_m * sig_m);
}

struct PureSpeciesTransport {
    std::vector<double> mu;      // pure-species dynamic viscosity [Pa·s]
    std::vector<double> k;       // pure-species thermal conductivity [W/(m·K)]
    std::vector<double> dmu_dT;  // [Pa*s/K], analytic
    std::vector<double> dk_dT;   // [W/(m*K^2)], analytic
};

// max(0, x), C2: on |x| < w the slope is the quintic smoothstep
// S(s) = 6s^5 - 15s^4 + 10s^3, s = (x/w + 1)/2, integrated, so value, slope
// and curvature all match at x = +-w. The value at x = 0 is 0.15625 w.
double smooth_positive_part(double x, double w, double& dfdx) {
    if (x <= -w) {
        dfdx = 0.0;
        return 0.0;
    }
    if (x >= w) {
        dfdx = 1.0;
        return x;
    }
    const double s = 0.5 * (x / w + 1.0);
    const double s3 = s * s * s;
    dfdx = s3 * (10.0 + s * (-15.0 + 6.0 * s));
    return 2.0 * w * s3 * s * (2.5 + s * (-3.0 + s));
}

// Parker temperature correction to Z_rot (Kee 2003 eq. 12.112) and its
// derivative in T*.
double parker_fz(double ts) {
    return 1.0 + std::pow(M_PI, 1.5) / std::sqrt(ts) * (0.5 + 1.0 / ts) +
           (M_PI * M_PI / 4.0 + 2.0) / ts;
}
double parker_fz_dts(double ts) {
    return std::pow(M_PI, 1.5) * (-0.25 * std::pow(ts, -1.5) - 1.5 * std::pow(ts, -2.5)) -
           (M_PI * M_PI / 4.0 + 2.0) / (ts * ts);
}

PureSpeciesTransport pure_species_transport(double T_in, const std::vector<double>& X)
{
    // Below 10 K the state is held (and so is everything derived from it).
    const double T = std::max(T_in, 10.0);
    const double dT_dTin = (T_in > 10.0) ? 1.0 : 0.0;

    const std::size_t N = X.size();
    PureSpeciesTransport out;
    out.mu.resize(N);
    out.k.resize(N);
    out.dmu_dT.resize(N);
    out.dk_dT.resize(N);

    for (std::size_t i = 0; i < N; ++i) {
        const double eps    = transport_props[i].well_depth;
        const double mw_kg  = molar_masses[i] / 1000.0;              // kg/mol
        const double diam   = transport_props[i].diameter * 1.0e-10; // m
        const double T_star = T / eps;
        const double d_star = compute_delta_star(transport_props[i].well_depth,
                                                 transport_props[i].diameter,
                                                 transport_props[i].dipole_moment);
        const Omega22Result om = omega22_and_derivative(T_star, d_star);
        const double m_mol  = mw_kg / thermo::AVOGADRO;              // kg/molecule

        // Kinetic theory viscosity: mu = (5/16) sqrt(pi*m*k_B*T) / (pi*sigma^2*Omega)
        out.mu[i] = (5.0 / 16.0) * std::sqrt(M_PI * m_mol * thermo::BOLTZMANN * T) /
                    (M_PI * diam * diam * om.omega);
        // d ln mu / dT = 1/(2T) - (dOmega/dT*) / (Omega eps)
        const double dlnmu = 0.5 / T - om.domega_dTstar / (om.omega * eps);
        out.dmu_dT[i] = out.mu[i] * dlnmu * dT_dTin;

        // Mason-Monchick modified Eucken thermal conductivity
        // Formula from Kee, Coltrin & Glarborg (2003) as implemented in Cantera.
        // All cv_*_R are dimensionless (in units of R per mole).

        // cv_rot in units of R: nrot/2 (Atom=0, Linear=1, Nonlinear=1.5)
        double cv_rot_R = 0.0;
        switch (transport_props[i].geometry) {
            case MolecularGeometry::Atom:      cv_rot_R = 0.0; break;
            case MolecularGeometry::Linear:    cv_rot_R = 1.0; break;
            case MolecularGeometry::Nonlinear: cv_rot_R = 1.5; break;
        }

        // cv_vib from NASA: cp/R - 5/2 - cv_rot/R, clamped to 0 at low T
        // (H2 below ~355 K, CH4 ~178 K, O2 ~189 K) by a C2 smooth positive
        // part (#611; the hard clamp stepped dk/dT up to 4%). For an atom the
        // raw value is cp/R - 5/2: zero (+-1e-9 round-off, which flipped the
        // hard clamp's derivative) until electronic excitation at high T.
        const double cv_vib_raw = cp_R(i, T) - 2.5 - cv_rot_R;
        double dpos = 0.0;
        const double cv_vib_R = smooth_positive_part(cv_vib_raw, CV_VIB_SMOOTH_HALF_WIDTH, dpos);
        const double dcv_vib = dpos * dcp_R_dT(i, T);

        // rho*D/mu ~ 6/5 (kinetic theory approximation)
        const double f_int_val = 1.2;
        const double A_factor  = 2.5 - f_int_val;  // ~ 1.3

        const double z_rot = transport_props[i].z_rot;
        double z_rot_eff = z_rot;
        double dz_rot = 0.0;
        if (z_rot > 0.0) {
            const double tstar_298 = 298.0 / eps;
            const double fz = parker_fz(T_star);
            z_rot_eff = z_rot * parker_fz(tstar_298) / fz;
            dz_rot = -z_rot_eff * parker_fz_dts(T_star) / fz / eps;
        }

        const double B_factor = z_rot_eff + (2.0 / M_PI) * (5.0 / 3.0 * cv_rot_R + f_int_val);
        const double c1       = (2.0 / M_PI) * A_factor / B_factor;
        const double dc1      = -c1 * dz_rot / B_factor;
        const double f_rot    = f_int_val * (1.0 + c1);
        const double f_trans  = 2.5 * (1.0 - c1 * cv_rot_R / 1.5);

        const double bracket = f_trans * 1.5 + f_rot * cv_rot_R + f_int_val * cv_vib_R;
        const double dbracket = -2.5 * dc1 * cv_rot_R + f_int_val * dc1 * cv_rot_R +
                                f_int_val * dcv_vib;
        const double scale = thermo::R_GAS / mw_kg;
        out.k[i] = out.mu[i] * scale * bracket;
        out.dk_dT[i] = (out.dmu_dT[i] * bracket + out.mu[i] * dbracket * dT_dTin) * scale;
    }

    return out;
}

// Wilke mixing rule for viscosity given pre-computed pure-species μᵢ.
double wilke_viscosity(const std::vector<double>& X,
                       const std::vector<double>& pure_mu)
{
    const std::size_t N = X.size();
    double mix_visc = 0.0;
    for (std::size_t i = 0; i < N; ++i) {
        if (X[i] <= 0.0) continue;
        double denom = 0.0;
        for (std::size_t j = 0; j < N; ++j) {
            if (X[j] <= 0.0) continue;
            double phi_ij;
            if (i == j) {
                phi_ij = 1.0;
            } else {
                const double M_i   = molar_masses[i];
                const double M_j   = molar_masses[j];
                const double term1 = 1.0 / std::sqrt(8.0) / std::sqrt(1.0 + M_i / M_j);
                const double term2 = std::pow(1.0 + std::sqrt(pure_mu[i] / pure_mu[j]) *
                                     std::pow(M_j / M_i, 0.25), 2);
                phi_ij = term1 * term2;
            }
            denom += X[j] * phi_ij;
        }
        mix_visc += X[i] * pure_mu[i] / denom;
    }
    return mix_visc;
}

// Mixture thermal conductivity (average of upper/lower bounds) given pre-computed kᵢ.
double mixture_conductivity(const std::vector<double>& X,
                            const std::vector<double>& pure_k)
{
    double sum1 = 0.0;
    double sum2 = 0.0;
    for (std::size_t i = 0; i < X.size(); ++i) {
        if (X[i] <= 0.0) continue;
        sum1 += X[i] * pure_k[i];
        sum2 += X[i] / pure_k[i];
    }
    return 0.5 * (sum1 + 1.0 / sum2);
}

// d mu_mix / dT for Wilke's rule: mu_mix = sum_i x_i mu_i / D_i with
// D_i = sum_j x_j phi_ij, phi_ij = a_ij (1 + sqrt(mu_i/mu_j) b_ij)^2.
double wilke_viscosity_dT(const std::vector<double>& X, const std::vector<double>& mu,
                          const std::vector<double>& dmu)
{
    const std::size_t N = X.size();
    double out = 0.0;
    for (std::size_t i = 0; i < N; ++i) {
        if (X[i] <= 0.0) continue;
        double D = 0.0;
        double dD = 0.0;
        for (std::size_t j = 0; j < N; ++j) {
            if (X[j] <= 0.0) continue;
            if (i == j) {
                D += X[j];
                continue;
            }
            const double M_i = molar_masses[i];
            const double M_j = molar_masses[j];
            const double a_ij = 1.0 / std::sqrt(8.0) / std::sqrt(1.0 + M_i / M_j);
            const double b_ij = std::pow(M_j / M_i, 0.25);
            const double r = std::sqrt(mu[i] / mu[j]);
            const double dr = 0.5 * r * (dmu[i] / mu[i] - dmu[j] / mu[j]);
            const double g = 1.0 + r * b_ij;
            D += X[j] * a_ij * g * g;
            dD += X[j] * a_ij * 2.0 * g * b_ij * dr;
        }
        out += X[i] * (dmu[i] / D - mu[i] * dD / (D * D));
    }
    return out;
}

// d mu_mix / dx_k at fixed T for Wilke's rule, x unnormalised:
//   d mu_mix / dx_k = mu_k / D_k - sum_i x_i mu_i phi_ik / D_i^2.
// For a species absent from the mixture (x_k = 0) this is the one-sided
// derivative as it enters: D_k is its row over the species present.
std::vector<double> wilke_viscosity_dX(const std::vector<double>& X,
                                       const std::vector<double>& mu)
{
    const std::size_t N = X.size();
    auto phi = [&](std::size_t i, std::size_t j) {
        if (i == j) {
            return 1.0;
        }
        const double M_i = molar_masses[i];
        const double M_j = molar_masses[j];
        const double a_ij = 1.0 / std::sqrt(8.0) / std::sqrt(1.0 + M_i / M_j);
        const double g = 1.0 + std::sqrt(mu[i] / mu[j]) * std::pow(M_j / M_i, 0.25);
        return a_ij * g * g;
    };
    std::vector<double> D(N, 0.0);
    for (std::size_t i = 0; i < N; ++i) {
        for (std::size_t j = 0; j < N; ++j) {
            if (X[j] > 0.0) {
                D[i] += X[j] * phi(i, j);
            }
        }
    }
    std::vector<double> out(N, 0.0);
    for (std::size_t k = 0; k < N; ++k) {
        double s = (D[k] > 0.0) ? mu[k] / D[k] : 0.0;
        for (std::size_t i = 0; i < N; ++i) {
            if (X[i] > 0.0) {
                s -= X[i] * mu[i] * phi(i, k) / (D[i] * D[i]);
            }
        }
        out[k] = s;
    }
    return out;
}

// d k_mix / dT for k_mix = (sum x_i k_i + 1 / sum x_i/k_i) / 2.
double mixture_conductivity_dT(const std::vector<double>& X, const std::vector<double>& k,
                               const std::vector<double>& dk)
{
    double s1 = 0.0, s2 = 0.0, ds2 = 0.0;
    for (std::size_t i = 0; i < X.size(); ++i) {
        if (X[i] <= 0.0) continue;
        s1 += X[i] * dk[i];
        s2 += X[i] / k[i];
        ds2 -= X[i] * dk[i] / (k[i] * k[i]);
    }
    return 0.5 * (s1 - ds2 / (s2 * s2));
}

// d k_mix / dx_k for k_mix = (sum x_i k_i + 1 / sum x_i/k_i) / 2, x
// unnormalised: (k_k - (1/k_k) / s2^2) / 2, s2 = sum x_i / k_i over the
// species present.
std::vector<double> mixture_conductivity_dX(const std::vector<double>& X,
                                            const std::vector<double>& k)
{
    double s2 = 0.0;
    for (std::size_t i = 0; i < X.size(); ++i) {
        if (X[i] > 0.0) {
            s2 += X[i] / k[i];
        }
    }
    std::vector<double> out(X.size(), 0.0);
    for (std::size_t i = 0; i < X.size(); ++i) {
        out[i] = 0.5 * (k[i] - (1.0 / k[i]) / (s2 * s2));
    }
    return out;
}

